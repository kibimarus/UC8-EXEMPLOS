-- CHAVE ESTRANGEIRA- FOREIGN KEY
-- AUTOINCREMENT = Adiciona sozinho o id
-- (Sem precisar colocar manualmente no INSERT INTO)
-- UNIQUE = ÚNICO = NENHUM OUTRO GENERO PODE TER O MESMO NOME
-- UNIQUE = BEIRA  A SER UMA CHAVE PRIMÁRIA
CREATE TABLE Genero(
    id_genero INTEGER PRIMARY KEY AUTOINCREMENT,
    nome VARCHAR(100) UNIQUE

);

-- NOT NULL = NÃO NULO = INFORMAÇÃO OBRIGATÓRIA
-- A CHAVE ESTRANGEIRA DEVE SER DO MESMO TIPO (INTEGER) 
CREATE TABLE Serie(
    id_serie INTEGER PRIMARY KEY AUTOINCREMENT,
    nome VARCHAR(255) NOT NULL,
    ano INTEGER,
    id_genero INTEGER,
    FOREIGN KEY (id_genero) REFERENCES Genero(id_genero)
);

